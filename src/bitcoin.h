#pragma once
#include <array>
#include <string>
#include <cstdint>

// ============================================================================
// Инициализация и очистка библиотеки secp256k1.
// ВАЖНО: эти функции используют thread_local контекст,
// поэтому каждый поток должен вызвать их самостоятельно.
// ============================================================================
void InitSecp256k1();
void CleanupSecp256k1();

// ============================================================================
// Принимает hex-строку перестановки (например "45555666889AAABCDF"),
// дополняет её нулями слева до 32 байт (64 hex-символа),
// интерпретирует как приватный ключ и возвращает сжатый публичный ключ (33 байта).
// ============================================================================
std::array<uint8_t, 33> HexPermToCompressedPubKey(const std::string& hexPerm);

// ============================================================================
// Вычисляет HASH160 от публичного ключа: RIPEMD160(SHA256(pubkey)).
// Результат — 20 байт, это именно тот идентификатор,
// который сравнивается с целями Puzzle 71-79.
// ============================================================================
void PubKeyToHash160(const uint8_t* pubkey, size_t len, uint8_t out[20]);

// ============================================================================
// Вспомогательная функция: преобразует массив байт в hex-строку.
// Используется только для отладочного вывода, не в горячем цикле.
// ============================================================================
std::string BytesToHex(const uint8_t* data, size_t len);