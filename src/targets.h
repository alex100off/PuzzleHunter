#pragma once
#include <cstdint>
#include <string>
#include <vector>

// ============================================================================
// Структура, описывающая одну цель для поиска.
// name    — человекочитаемое имя (например "Puzzle 71")
// hash160 — 20-байтный HASH160 публичного ключа, с которым сравниваем кандидатов
// ============================================================================
struct Target
{
    std::string name;
    uint8_t     hash160[20];
};

// ============================================================================
// Инициализация таблицы целей.
// Вызывается один раз в начале работы программы.
// Здесь можно загрузить цели из файла или захардкодить известные Puzzle.
// ============================================================================
void InitTargets();

// ============================================================================
// Проверка: совпадает ли HASH160 кандидата с какой-либо целью.
// Если совпадение найдено — возвращает true и заполняет foundTarget.
// Если нет — возвращает false.
// ============================================================================
bool CheckHash160(const uint8_t hash160[20], Target& foundTarget);

// ============================================================================
// Запись найденного совпадения в лог-файл.
// Сохраняет: имя цели, перестановку, публичный ключ, HASH160.
// ============================================================================
void LogFoundKey(
    const Target& target,
    const std::string& permutation,
    const uint8_t pubkey[33],
    const uint8_t hash160[20]);

// ============================================================================
// Получение списка всех целей (для отладки и статистики).
// ============================================================================
const std::vector<Target>& GetTargets();